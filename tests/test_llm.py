class TestEnrichErrorHandling:
    @patch("saturation_meter.llm._call_backend", side_effect=ImportError("pip install openai"))
    def test_import_error_adds_warning(self, _mock):
        report = make_saturated_report()
        result = enrich_with_narrative(report, backend="openai")
        assert result.narrative is None
        assert any("LLM narrative generation failed" in w for w in result.warnings)

    @patch("saturation_meter.llm._call_backend", side_effect=RuntimeError("API error"))
    def test_runtime_error_adds_warning(self, _mock):
        report = make_saturated_report()
        result = enrich_with_narrative(report, backend="anthropic")
        assert result.narrative is None
        assert any("LLM narrative generation failed" in w for w in result.warnings)

    @patch("saturation_meter.llm._call_backend", side_effect=Exception("timeout"))
    def test_any_exception_does_not_raise(self, _mock):
        report = make_saturated_report()
        # Should NOT raise — errors are captured as warnings
        result = enrich_with_narrative(report, backend="gemini")
        assert result is not None

    @patch("saturation_meter.llm._call_backend", side_effect=RuntimeError("fail"))
    def test_existing_warnings_preserved_on_error(self, _mock):
        report = make_unsaturated_report()
        pre_existing = list(report.warnings)
        assert len(pre_existing) > 0
        enrich_with_narrative(report, backend="openai")
        for w in pre_existing:
            assert w in report.warnings


