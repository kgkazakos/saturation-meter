from unittest.mock import MagicMock, patch

import pytest

from saturation_meter.core import analyze_saturation
from saturation_meter.llm import (
    _build_context,
    _call_backend,
    enrich_with_narrative,
)
from saturation_meter.models import InterviewEntry


# ---------------------------------------------------------------------------
# Fixtures
# ---------------------------------------------------------------------------


def make_saturated_report():
    interviews = [
        InterviewEntry("P01", ["cognitive_load", "feature_overload", "navigation_confusion",
                                "trust_deficit", "onboarding_friction"]),
        InterviewEntry("P02", ["cognitive_load", "feature_overload", "information_overload"]),
        InterviewEntry("P03", ["trust_deficit", "cognitive_load", "feature_overload"]),
        InterviewEntry("P04", ["cognitive_load", "feature_overload", "navigation_confusion"]),
        InterviewEntry("P05", ["cognitive_load", "feature_overload", "navigation_confusion"]),
        InterviewEntry("P06", ["cognitive_load", "feature_overload", "navigation_confusion"]),
    ]
    return analyze_saturation(interviews)


def make_unsaturated_report():
    interviews = [
        InterviewEntry("P01", ["a", "b", "c"]),
        InterviewEntry("P02", ["d", "e", "f"]),
    ]
    return analyze_saturation(interviews)


FAKE_NARRATIVE = "This is a methodological narrative generated by the LLM."


# ---------------------------------------------------------------------------
# _build_context
# ---------------------------------------------------------------------------


class TestBuildContext:
    def test_returns_string(self):
        report = make_saturated_report()
        ctx = _build_context(report)
        assert isinstance(ctx, str)

    def test_contains_total_interviews(self):
        report = make_saturated_report()
        ctx = _build_context(report)
        assert str(report.total_interviews) in ctx

    def test_contains_total_unique_themes(self):
        report = make_saturated_report()
        ctx = _build_context(report)
        assert str(report.total_unique_themes) in ctx

    def test_contains_saturation_status_saturated(self):
        report = make_saturated_report()
        ctx = _build_context(report)
        assert "Saturation detected" in ctx

    def test_contains_saturation_status_not_saturated(self):
        report = make_unsaturated_report()
        ctx = _build_context(report)
        assert "not yet detected" in ctx.lower()

    def test_contains_participant_ids(self):
        report = make_saturated_report()
        ctx = _build_context(report)
        assert "P01" in ctx

    def test_contains_stop_recommendation(self):
        report = make_saturated_report()
        ctx = _build_context(report)
        assert report.stop_recommendation in ctx

    def test_theme_truncation_at_20(self):
        interviews = [
            InterviewEntry("P01", [f"theme_{i}" for i in range(30)]),
        ]
        report = analyze_saturation(interviews)
        ctx = _build_context(report)
        # Should mention the overflow count
        assert "+10" in ctx

    def test_warnings_included_when_present(self):
        report = make_unsaturated_report()
        assert len(report.warnings) > 0
        ctx = _build_context(report)
        assert report.warnings[0][:20] in ctx


