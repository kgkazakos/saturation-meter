class TestEnrichWithNarrative:
    @patch("saturation_meter.llm._call_backend", return_value=FAKE_NARRATIVE)
    def test_narrative_attached_to_report(self, _mock):
        report = make_saturated_report()
        result = enrich_with_narrative(report, backend="anthropic")
        assert result.narrative == FAKE_NARRATIVE

    @patch("saturation_meter.llm._call_backend", return_value=FAKE_NARRATIVE)
    def test_returns_same_report_object(self, _mock):
        report = make_saturated_report()
        result = enrich_with_narrative(report, backend="openai")
        assert result is report

    @patch("saturation_meter.llm._call_backend", return_value=FAKE_NARRATIVE)
    def test_metrics_unchanged_after_enrichment(self, _mock):
        report = make_saturated_report()
        original_saturated = report.is_saturated
        original_total = report.total_interviews
        enrich_with_narrative(report, backend="gemini")
        assert report.is_saturated == original_saturated
        assert report.total_interviews == original_total

    @patch("saturation_meter.llm._call_backend", return_value=FAKE_NARRATIVE)
    def test_backend_passed_to_call_backend(self, mock_fn):
        report = make_saturated_report()
        enrich_with_narrative(report, backend="gemini")
        args = mock_fn.call_args
        assert args[0][0] == "gemini"

    @patch("saturation_meter.llm._call_backend", return_value=FAKE_NARRATIVE)
    def test_prompt_contains_context(self, mock_fn):
        report = make_saturated_report()
        enrich_with_narrative(report, backend="anthropic")
        prompt_arg = mock_fn.call_args[0][1]
        assert isinstance(prompt_arg, str)
        assert len(prompt_arg) > 50  # non-trivial prompt


